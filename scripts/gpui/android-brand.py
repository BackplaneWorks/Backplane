#!/usr/bin/env python3
"""Android vector drawables for the in-app brand mark, from the web's own assets:
src/web/favicon.svg (dark theme: the raster apple-touch-icon is the same art) and src/web/favicon-light.svg
(light theme, commit 80cc30e499). Writes mobile/android/app/src/main/res/drawable/brand_{dark,light}.xml.
Run it after scripts/icons.sh; test/gpui/visual/ checks the rendered result."""
import re, os
root = os.path.abspath(os.path.join(os.path.dirname(__file__), "../.."))
out = root + "/mobile/android/app/src/main/res/drawable"
for name, src in (("dark", "favicon.svg"), ("light", "favicon-light.svg")):
    s = open(f"{root}/src/web/{src}").read()
    bg = re.search(r'<rect[^>]*fill="(#[0-9a-fA-F]{6})"', s).group(1)
    fg = re.search(r'<path fill="(#[0-9a-fA-F]{6})"', s).group(1)
    d = re.search(r' d="([^"]+)"', s).group(1)
    tx, ty, sc = re.search(r'translate\(([\d.]+) ([\d.]+)\) scale\(([\d.]+)\)', s).groups()
    argb = lambda c: "#FF" + c[1:].upper()
    open(f"{out}/brand_{name}.xml", "w").write(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- generated by scripts/gpui/android-brand.py from src/web/{src}: do not edit -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="256dp"
    android:height="256dp"
    android:viewportWidth="256"
    android:viewportHeight="256">
    <path android:fillColor="{argb(bg)}" android:pathData="M0,0H256V256H0Z" />
    <group android:translateX="{tx}" android:translateY="{ty}" android:scaleX="{sc}" android:scaleY="{sc}">
        <path
            android:fillColor="{argb(fg)}"
            android:fillType="evenOdd"
            android:pathData="{d}" />
    </group>
</vector>
''')
    print(name, bg, fg)

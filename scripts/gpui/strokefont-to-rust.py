#!/usr/bin/env python3
"""src/core/strokefont.bend's glyph table as native/host/src/kicad/strokefont_data.rs (generated; run again if the Bend table changes;
--check fails when the Rust file is stale)."""
import os, re, sys
R = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
t = open(os.path.join(R, "src/core/strokefont.bend")).read()
def glyph(s):
    m = re.match(r"\s*Glyph\{(\d+), (\d+), \[(.*)\]\}\s*$", s, re.S)
    l, r, body = int(m[1]), int(m[2]), m[3]
    ss = re.findall(r"\[((?:GP\{\d+, \d+\}(?:, )?)+)\]", body)
    return l, r, [[(int(a), int(b)) for a, b in re.findall(r"GP\{(\d+), (\d+)\}", x)] for x in ss]
def lit(g):
    l, r, ss = g
    return "Glyph { l: %d, r: %d, strokes: &[%s] }" % (l, r, ", ".join("&[" + ", ".join("(%d, %d)" % p for p in s) + "]" for s in ss))
box = glyph(re.search(r"def Stroke\.box\(\) -> Glyph:\n(.*)\n", t)[1])
ohm = glyph(re.search(r"def Stroke\.ohm\(\) -> Glyph:\n(.*)\n", t)[1])
low = t[t.index("def Stroke.low"):t.index("def Stroke.ohm")]
cases = re.findall(r"    case (\d+)n:\n(      Glyph\{.*)\n", low)
assert re.search(r"    case _:\n      Stroke\.box\(\)", low)
o = ["// Generated by scripts/gpui/strokefont-to-rust.py from src/core/strokefont.bend. Do not edit.", "use super::strokefont::Glyph;",
     "pub static BOX: Glyph = %s;" % lit(box), "pub static OHM: Glyph = %s;" % lit(ohm)]
for n, g in cases: o.append("static G%s: Glyph = %s;" % (n, lit(glyph(g))))
o.append("/// Stroke.low: printable ASCII and a few Latin-1 signs, else the box.\npub fn low(cp: u32) -> &'static Glyph {\n    match cp {")
for n, _ in cases: o.append("        %s => &G%s," % (n, n))
o.append("        _ => &BOX,\n    }\n}\n")
s = "\n".join(o)
p = os.path.join(R, "native/host/src/kicad/strokefont_data.rs")
if "--check" in sys.argv:
    sys.exit(0 if open(p).read() == s else "strokefont_data.rs is stale")
open(p, "w").write(s); print(len(cases), "glyphs")

#!/usr/bin/env python3
"""Every view action name of client.bend's `Ui.act` table (Ui.actions() and Menu.actions()), with who answers it in Rust.
  covered   a Rust function answers it and a pair recorded from bp-policy states it (test/gpui/commands/fixtures/actions.json)
  hand case a Rust function answers it, stated by a hand-written case from the Bend source (the recorded helper does not answer it as the source says)
  session   the session module's (parity-session): select, row-delete's two-step confirm
  helper    not ported: the Bend helper answers it (on a real-size log: a retryable "not ported", PRESENTER-PORT.md)
usage: scripts/gpui/actions-coverage.py [--check]     (default writes docs/gpui/ACTIONS.md)"""
import json, os, re, subprocess, sys
ROOT = subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True, cwd=os.path.dirname(os.path.abspath(__file__))).strip()
def read(p): return open(os.path.join(ROOT, p)).read()
client = read("src/core/client.bend")
def lst(defn):
    m = re.search(r"def %s\(\) -> List<&2, String>:\n(.*?)\n\n" % re.escape(defn), client, re.S)
    return re.findall(r'"([^"]*)"', m.group(1))
names = []
for n in lst("Ui.actions") + lst("Menu.actions"):
    if n not in names: names.append(n)
ported = set(re.findall(r'^\s*"([a-z-]+)"(?: \| "[a-z-]+")* (?:=>|\|)', read("native/host/src/commands/actions.rs"), re.M))
body = read("native/host/src/commands/actions.rs"); ported = set()
for m in re.finditer(r'^        ((?:"[a-z-]+"(?: \| )?)+) (?:=>)', body, re.M): ported |= set(re.findall(r'"([a-z-]+)"', m.group(1)))
fx = json.load(open(os.path.join(ROOT, "test/gpui/commands/fixtures/actions.json")))
recorded = {s["action"] for s in fx["steps"]}
session = {"select"}
rows = []
for n in names:
    st = "covered" if n in ported and n in recorded else ("hand case" if n in ported else ("session" if n in session else "helper"))
    rows.append((n, st))
if "--check" in sys.argv:
    print("hand cases:", [n for n, s in rows if s == "hand case"]); sys.exit(0)
c = {}
for _, s in rows: c[s] = c.get(s, 0) + 1
out = ["# View actions: who answers them in Rust", "", "Generated by `scripts/gpui/actions-coverage.py` from client.bend's `Ui.actions()` and `Menu.actions()`; `commands/actions.rs` is the table, "
       "`test/gpui/commands/fixtures/actions.json` the pairs recorded from bp-policy. A recorded pair is a test, not the contract: where the JS replay differs, JS wins.", "",
       "Counts: " + ", ".join(f"{k} {v}" for k, v in sorted(c.items())) + f" of {len(rows)}.", "", "| action | status |", "|---|---|"]
out += [f"| `{n}` | {s} |" for n, s in rows]
open(os.path.join(ROOT, "docs/gpui/ACTIONS.md"), "w").write("\n".join(out) + "\n")
print("wrote docs/gpui/ACTIONS.md:", c)

#!/usr/bin/env python3
"""Generate pure Unicode search keys: NFD, casefold, then remove marks.

Use the same table for candidates and queries; keep displayed text intact.
The version is pinned so another Python cannot silently change the index.
"""
from pathlib import Path
from collections import defaultdict
import unicodedata as u
assert u.unidata_version == '16.0.0', u.unidata_version

def folded(s):
    return ''.join(c for c in u.normalize('NFD', u.normalize('NFD', s).casefold()) if not u.category(c).startswith('M'))

def literal(s):
    return '"' + ''.join('\\u{' + format(ord(c), 'x') + '}' for c in s) + '"'

pages=defaultdict(str)
drops=defaultdict(list)
for n in range(128,0x110000):
    if 0xAC00 <= n <= 0xD7A3: continue
    c=chr(n);s=folded(c)
    if s!=c:
        if s: pages[n>>8]+=c+s+'\0'
        elif drops[n>>8] and n==drops[n>>8][-1][1]+1: drops[n>>8][-1][1]=n
        else: drops[n>>8].append([n,n])
text='''import Base

# Generated by scripts/search-fold-gen.py, Unicode 16.0.0.
# Each page holds key, replacement, NUL records. ASCII has no table walk.
def Fold.page(c: U32) -> String:
  match c:
'''
for n,s in sorted(pages.items()): text+=f'    case {n}: {literal(s)}\n'
text+='    case _: ""\n\n# Marks that disappear are kept as compact, per-page ranges.\ndef Fold.removed.page(c: U32) -> String:\n  match c:\n'
for n,rs in sorted(drops.items()): text+=f'    case {n}: {literal("".join(chr(a)+chr(b) for a,b in rs))}\n'
text+='''    case _: ""

def Fold.removed.go(s: String, +c: U32, found: Bool) -> Bool:
  match s found:
    case _ True{}: True{}
    case SCon{Chr{a}, SCon{Chr{b}, tail}} False{}:
      Fold.removed.go(tail, c, Bool.and(U32.is_ge(c, a), U32.is_le(c, b)))
    case _ False{}: False{}

def Fold.same(c: U32) -> String:
  SCon{Chr{c}, SNil{}}

type FoldScan is Data:
  FoldKey{}
  FoldSkip{}
  FoldTake{acc: String}
  FoldDone{text: String}

def Fold.key(hit: Bool) -> FoldScan:
  match hit:
    case True{}: FoldTake{""}
    case False{}: FoldSkip{}

def Fold.take(last: Bool, c: U32, acc: String) -> FoldScan:
  match last:
    case True{}: FoldDone{String.reverse(acc)}
    case False{}: FoldTake{SCon{Chr{c}, acc}}

def Fold.step(+c: U32, needle: U32, st: FoldScan) -> FoldScan:
  match st:
    case FoldKey{}: Fold.key(U32.is_eq(c, needle))
    case FoldSkip{}: Bool.pick(FoldScan, U32.is_eq(c, 0), FoldKey{}, FoldSkip{})
    case FoldTake{acc}: Fold.take(U32.is_eq(c, 0), c, acc)
    case FoldDone{text}: FoldDone{text}

def Fold.scan(s: String, +c: U32, st: FoldScan) -> String:
  match s st:
    case _ FoldDone{text}: text
    case SNil{} _: Fold.same(c)
    case SCon{Chr{h}, tail} _: Fold.scan(tail, c, Fold.step(h, c, st))

def Fold.canonical(removed: Bool, +c: U32) -> String:
  match removed:
    case True{}: ""
    case False{}: Fold.scan(Fold.page(U32.shrn(c, 8n)), c, FoldKey{})

# Hangul syllables decompose arithmetically rather than using 11,172 rows.
def Fold.hangul.tail(+n: U32) -> String:
  match n:
    case 0: ""
    case _: SCon{Chr{(4519 + n : U32)}, SNil{}}

def Fold.char.unicode(hangul: Bool, +c: U32) -> String:
  match hangul:
    case True{}:
      +n = {(c - 44032 : U32) : U32}
      SCon{Chr{(4352 + (n / 588 : U32) : U32)}, SCon{Chr{(4449 + ((n % 588 : U32) / 28 : U32) : U32)}, Fold.hangul.tail((n % 28 : U32))}}
    case False{}: Fold.canonical(Fold.removed.go(Fold.removed.page(U32.shrn(c, 8n)), c, False{}), c)

def Fold.ascii(+c: U32) -> String:
  Fold.same(Bool.pick(U32, Bool.and(U32.is_ge(c, 65), U32.is_le(c, 90)), (c + 32 : U32), c))

# Fullwidth ASCII is common in pasted searches; its fold is arithmetic.
def Fold.width(wide: Bool, +c: U32) -> String:
  match wide:
    case True{}: Fold.ascii((c - 65248 : U32))
    case False{}: Fold.char.unicode(Bool.and(U32.is_ge(c, 44032), U32.is_le(c, 55203)), c)

def Fold.char.ascii(ascii: Bool, +c: U32) -> String:
  match ascii:
    case True{}: Fold.ascii(c)
    case False{}: Fold.width(Bool.and(U32.is_ge(c, 65281), U32.is_le(c, 65374)), c)

def Fold.char(+c: U32) -> String:
  Fold.char.ascii(U32.is_lt(c, 128), c)

# Consume each input scalar once, keeping the walk safe for long replies.
def Fold.go(s: String, acc: String) -> String:
  match s:
    case SNil{}: String.reverse(acc)
    case SCon{Chr{c}, tail}: Fold.go(tail, String.reverse(Fold.char(c)) ++ acc)

def Fold.text(s: String) -> String:
  Fold.go(s, "")
'''
text+='''# ASCII capitals still mark camel-case word starts in the fuzzy scorer.
def Fold.title.char(+c: U32) -> String:
  Bool.pick(String, U32.is_lt(c, 128), Fold.same(c), Fold.char(c))

def Fold.title.go(s: String, acc: String) -> String:
  match s:
    case SNil{}: String.reverse(acc)
    case SCon{Chr{c}, tail}: Fold.title.go(tail, String.reverse(Fold.title.char(c)) ++ acc)

def Fold.title(s: String) -> String:
  Fold.title.go(s, "")
'''
Path('src/core/search-fold.bend').write_text(text)
print(f'{len(pages)} Unicode pages')

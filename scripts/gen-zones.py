#!/usr/bin/env python3
"""gen-zones.py ZONEINFO_DIR WINDOWS_TZ_PY > native/host/src/settings/zones_table.rs
The time zones a hub knows when its system has no zone files (Windows): each IANA zone's POSIX rule (the footer of its TZif file, as
settings/zone.rs reads it), and Windows' zone names mapped to IANA (CLDR's windowsZones, as tzlocal's windows_tz.py carries it; read as data).
Run again with a newer tzdata; zone.rs prefers the system's own files where they exist."""
import ast, os, sys
zdir, wtz = sys.argv[1], sys.argv[2]
zones = {}
for root, dirs, files in os.walk(zdir):
    if root == zdir: dirs[:] = [d for d in dirs if d not in ('posix', 'right', 'Etc')]   # copies, and Etc below by itself
    for f in files:
        p = os.path.join(root, f); name = os.path.relpath(p, zdir)
        if name.startswith(('posix', 'right')) or '.' in f or f in ('posixrules', 'localtime', 'Factory', 'leapseconds', 'tzdata.zi', 'SECURITY'): continue
        b = open(p, 'rb').read()
        if not b.startswith(b'TZif'): continue
        foot = b.rstrip(b'\n').rsplit(b'\n', 1)[-1]
        if foot and len(foot) < 80 and foot.isascii(): zones[name] = foot.decode()
for e in os.listdir(os.path.join(zdir, 'Etc')):
    b = open(os.path.join(zdir, 'Etc', e), 'rb').read()
    if b.startswith(b'TZif'): zones['Etc/' + e] = b.rstrip(b'\n').rsplit(b'\n', 1)[-1].decode()
t = ast.parse(open(wtz).read()); win = {}
for n in t.body:
    if isinstance(n, ast.Assign) and any(getattr(x, 'id', '') == 'win_tz' for x in n.targets): win = ast.literal_eval(n.value)
q = lambda s: '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
print('// Generated by scripts/gen-zones.py from tzdata and CLDR windowsZones: do not edit by hand.')
print('/// IANA zone -> POSIX rule (the footer of its TZif file), sorted by name.')
print('pub const ZONES: &[(&str, &str)] = &[')
for k in sorted(zones): print(f'    ({q(k)}, {q(zones[k])}),')
print('];')
print('/// Windows time zone key name -> IANA zone, sorted by name.')
print('pub const WINDOWS: &[(&str, &str)] = &[')
for k in sorted(win): print(f'    ({q(k)}, {q(win[k])}),')
print('];')

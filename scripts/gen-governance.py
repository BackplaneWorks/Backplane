#!/usr/bin/env python3
"""Generate the BP/GOV schema module, runtime policy registry, and reference."""
import argparse
import hashlib
from itertools import product
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "spec/governance.schema.json"
SOURCE = ROOT / "src/core/governance.bend"
MODULE = ROOT / "src/core/governance_schema.bend"
DOC = ROOT / "docs/governance.md"
POLICY = ROOT / "src/core/governance_policy.bend"


def schema_data():
    data = json.loads(SCHEMA.read_text(encoding="utf-8"))
    required = {"protocol", "schema", "wire", "committee", "deployment", "receipt_fields", "render_certificate", "ledgers", "entities", "procedural_annex", "policy_registry"}
    if set(data) != required:
        raise ValueError("governance schema has missing or unexpected fields")
    if not data["protocol"].startswith("BP/GOV/") or not isinstance(data["schema"], int):
        raise ValueError("governance protocol/version is malformed")
    if len(data["committee"]) != 3 or len(data["ledgers"]) != 5:
        raise ValueError("expected three committee roles and five ledgers")
    if data["deployment"]["queue_limit_bytes"] != 268435456:
        raise ValueError("the governance queue limit is fixed at 256 MiB")
    registry = data["policy_registry"]
    if [len(registry[key]) for key in ("committee_roles", "review_checks", "peer_conditions", "durability_phases")] != [4, 8, 4, 8]:
        raise ValueError("the governance registry must retain its 4 x 8 x 4 x 8 policy product")
    if len(registry["batch_conditions"]) != 4 or len(registry["requirements"]) != 4 or len(registry["dispositions"]) != 4:
        raise ValueError("the governance registry requires four batch conditions, requirements, and dispositions")
    return data


def source_digest():
    return hashlib.sha256(SOURCE.read_bytes()).hexdigest()


def bend_string(value):
    return json.dumps(value, ensure_ascii=False)


def render_module(data):
    return (
        "# GENERATED by scripts/gen-governance.py from spec/governance.schema.json and governance.bend.\n"
        "# Regenerate: python3 scripts/gen-governance.py\n"
        "import Base\n\n"
        "def GovSchema.protocol() -> String:\n"
        f"  {bend_string(data['protocol'])}\n\n"
        "def GovSchema.version() -> Nat:\n"
        f"  {data['schema']}n\n\n"
        "def GovSchema.queue_limit() -> Nat:\n"
        f"  {data['deployment']['queue_limit_bytes']}n\n\n"
        "def GovSchema.source.digest() -> String:\n"
        f"  {bend_string(source_digest())}\n"
    )


def render_docs(data):
    ledgers = "\n".join(f"- `<home>/{row['path']}`: {row['purpose']}." for row in data["ledgers"])
    entities = "\n".join(
        f"- `{name}` mirrors: " + ", ".join(f"`{tag}`" for tag in tags) + "."
        for name, tags in data["entities"].items()
    )
    fields = ", ".join(f"`{field}`" for field in data["receipt_fields"])
    roles = ", ".join(f"`{role}`" for role in data["committee"])
    render = data["render_certificate"]
    deployment = data["deployment"]
    annex = data["procedural_annex"]
    stages = "\n".join(
        f"### {index}. {stage['name']}\n\n"
        f"- **Owner:** {stage['owner']}\n"
        f"- **Action:** {stage['action']}\n"
        f"- **Exit record:** {stage['exit']}"
        for index, stage in enumerate(annex["stages"], 1)
    )
    roles = "\n".join(
        f"| `{role['name']}` | {role['question']} | {role['record']} |"
        for role in annex["roles"]
    )
    artifacts = "\n".join(
        f"| `{artifact['name']}` | {artifact['producer']} | {artifact['consumer']} | {artifact['retention']} |"
        for artifact in annex["artifacts"]
    )
    glossary = "\n".join(
        f"| `{entry['term']}` | {entry['meaning']} |"
        for entry in annex["glossary"]
    )
    return f'''# {data["protocol"]}

<!-- GENERATED by scripts/gen-governance.py; edit spec/governance.schema.json. -->

Every non-empty durable hub commit is followed by one `GovernanceLogged` event in the same append to `events.jsonl`. The content-free receipt has {fields}. The write path recomputes its SHA-256 digest over canonical event encodings and checks it before persisting.

The local committee roles are {roles}; they are automatic policy checks, not people. In shadow mode, writes keep the earlier behavior until every paired hub advertises this protocol. Once active, a durable batch needs unanimous automatic ballots from every paired hub, including machines with thread sync turned off. Only the originating hub commits the batch; peers durably record their content-free ballots and never receive event bodies.

The FIFO queue is private at `<home>/{deployment["queue_path"]}` and capped at {deployment["queue_limit_bytes"]} bytes (256 MiB). A full queue rejects new writes with a retryable error. Pending batches and frozen rosters survive restart; offline peers keep the head waiting. Explicit unpairing removes that peer from the active roster and causes the remaining peers to vote again. A dissenting ballot rejects the batch. A second reading reruns checks and cannot change a rejection into approval.

The voter receipt ledger is private at `<home>/{deployment["vote_receipts_path"]}`. Signed `/far/rpc` requests carry only proposal id, protocol, sequence, roster, action tags, count, schema, and a digest of those fields. The digest does not cover event bodies.

Five rebuildable JSONL sidecars split the metadata by purpose:

{ledgers}

The event log is authoritative. After a successful event append, the hub appends these sidecars. If a sidecar write fails, the durable commit remains and the hub logs that the indexes need replay. Startup reconstructs all five from `events.jsonl`, writes each through a private temporary file, then renames it into place. A crash partway through rebuilding is repaired on the next startup.

The live state exposes the most recent receipt at `{data["wire"]["key"]}`. Older clients receive a `{data["wire"]["event"]}` projection for that key, preserving the event shape and sequence. The native window, web app, iOS, Android, and `plane_read` expose the same read-only Governance section; the label is translated in English and Japanese.

Command envelopes record actor, action, entity family, target, effect adapter, digest, and time. Entity mirrors normalize legacy event tags without copying their payloads:

{entities}

Unmapped event tags use the `System` family. Receipt and mirror rows omit message bodies, prompts, file paths, and effect output. Projection certificates store only a digest, count, protocol, receipt id, and verification result. A v1 receipt has no stored digest, so rebuild recomputes it from the event batch and marks the certificate as recomputed. Web and phone plane payloads also carry a render certificate using {render["algorithm"]} over `{render["input"]}`; it identifies the shared view model before client layout and rasterization.

The generated Bend schema records the protocol and source digest `{source_digest()}`. `scripts/gen-governance.py` renders this document and `src/core/governance_schema.bend`; `scripts/check.sh` rejects stale generated output. The source-digest import makes code edits feed the generator, while the generator must run before the type checker reads the generated module. `scripts/governance-cycle.sh` generates, checks, and regenerates in order to resolve that build dependency.

    The generated runtime policy registry contains 1,024 typed rules. Peer proposal validation walks the full registry and refuses review if a row is malformed, out of order, or missing from the generated sequence.

## Procedural assurance annex

**Status:** {annex["status"]}. This annex has no effect on event handling, voting, queue progression, or client state. Its purpose is to document the process of documenting the process: {annex["purpose"]}

The sequence below is a reading order for a hypothetical review packet. It does not add gates to the executable path. Each stage produces a record so the next stage can establish that the prior stage produced a record.

{stages}

### Responsibility and evidence matrix

The roles below describe questions a hypothetical review could ask and records it could retain. They are not runtime identities and do not receive ballots.

| Role | Review question | Retained record |
| --- | --- | --- |
{roles}

### Artifact custody matrix

These artifacts are proposed paperwork for the annex only. They are not files written by Backplane.

| Artifact | Producer | Consumer | Retention statement |
| --- | --- | --- | --- |
{artifacts}

### Terminology register

| Term | Meaning |
| --- | --- |
{glossary}
'''


def render_policy(data):
    policy = data["policy_registry"]
    combinations = list(product(
        policy["committee_roles"], policy["review_checks"], policy["peer_conditions"], policy["durability_phases"]
    ))
    chunk_size = 32
    rows = [
        "# GENERATED by scripts/gen-governance.py; edit spec/governance.schema.json.",
        "import Base",
        "",
        "type GovPolicyRule is Data:",
        "  GovPolicyRule{id: String, role: String, check: String, peer: String, batch: String, phase: String, requirement: String, disposition: String}",
        "",
        "def GovPolicy.in.go(names: List<&2, String>, +value: String) -> Bool:",
        "  match names:",
        "    case Nil{}:",
        "      False{}",
        "    case name <> rest:",
        "      Bool.or(String.eq(name, value), GovPolicy.in.go(rest, value))",
        "",
        "def GovPolicyRule.valid(rule: GovPolicyRule) -> Bool:",
        "  match rule:",
        "    case GovPolicyRule{+id, +role, +check, +peer, +batch, +phase, +requirement, +disposition}:",
        "      +present = Bool.and(Bool.not(String.is_empty(id)), Bool.and(Bool.not(String.is_empty(role)),",
        "        Bool.and(Bool.not(String.is_empty(check)), Bool.and(Bool.not(String.is_empty(peer)),",
        "          Bool.and(Bool.not(String.is_empty(batch)), Bool.and(Bool.not(String.is_empty(phase)),",
        "            Bool.and(Bool.not(String.is_empty(requirement)), Bool.not(String.is_empty(disposition)))))))))",
        "      +classified = Bool.and(GovPolicy.in.go([" + ", ".join(json.dumps(x) for x in policy["committee_roles"]) + "], role),",
        "        Bool.and(GovPolicy.in.go([" + ", ".join(json.dumps(x) for x in policy["review_checks"]) + "], check),",
        "          Bool.and(GovPolicy.in.go([" + ", ".join(json.dumps(x) for x in policy["peer_conditions"]) + "], peer),",
        "            Bool.and(GovPolicy.in.go([" + ", ".join(json.dumps(x) for x in policy["batch_conditions"]) + "], batch),",
        "              Bool.and(GovPolicy.in.go([" + ", ".join(json.dumps(x) for x in policy["durability_phases"]) + "], phase),",
        "                Bool.and(GovPolicy.in.go([" + ", ".join(json.dumps(x) for x in policy["requirements"]) + "], requirement),",
        "                  GovPolicy.in.go([" + ", ".join(json.dumps(x) for x in policy["dispositions"]) + "], disposition)))))))",
        "      Bool.and(present, classified)",
        "",
        "def GovPolicyRule.id(rule: GovPolicyRule) -> String:",
        "  match rule:",
        "    case GovPolicyRule{id, _, _, _, _, _, _, _}:",
        "      id",
        "",
        "def GovPolicy.registry.valid.go(+rules: List<&2, GovPolicyRule>, +seen: Nat, +end: Nat) -> Bool:",
        "  match rules:",
        "    case Nil{}:",
        "      Nat.is_eq(seen, end)",
        "    case +rule <> rest:",
        "      +identity = String.eq(GovPolicyRule.id(rule), \"BP-GOV-RULE-\" ++ Nat.show(1n+seen))",
        "      Bool.and(identity, Bool.and(GovPolicyRule.valid(rule), GovPolicy.registry.valid.go(rest, 1n+seen, end)))",
        "",
    ]
    entries = []
    for number, (role, check, peer, phase) in enumerate(combinations, 1):
        batch = policy["batch_conditions"][(number - 1) % len(policy["batch_conditions"])]
        requirement = policy["requirements"][(number - 1) % len(policy["requirements"])]
        disposition = policy["dispositions"][(number - 1) % len(policy["dispositions"])]
        fields = [
            f"BP-GOV-RULE-{number}", role, check, peer, batch, phase, requirement, disposition,
        ]
        entries.append("    GovPolicyRule{\n" + ",\n".join(f"      {json.dumps(field)}" for field in fields) + "\n    }")
    chunks = [entries[i:i + chunk_size] for i in range(0, len(entries), chunk_size)]
    names = [f"chunk_{i:02d}" for i in range(len(chunks))]
    for name, chunk in zip(names, chunks):
        rows.extend([
            f"def GovPolicy.rules.{name}() -> List<&2, GovPolicyRule>:",
            "  [",
            ",\n".join(chunk),
            "  ]",
            "",
        ])
    append = "Nil{}"
    for name in reversed(names):
        append = f"List.append(&2, GovPolicyRule, GovPolicy.rules.{name}(), {append})"
    rows.extend([
        "def GovPolicy.rules() -> List<&2, GovPolicyRule>:",
        f"  {append}",
        "",
    ])
    checks = [
        f"GovPolicy.registry.valid.go(GovPolicy.rules.{name}(), {index * chunk_size}n, {index * chunk_size + len(chunk)}n)"
        for index, (name, chunk) in enumerate(zip(names, chunks))
    ]
    valid = checks[-1]
    for check in reversed(checks[:-1]):
        valid = f"Bool.and({check}, {valid})"
    rows.extend([
        "def GovPolicy.registry.valid() -> Bool:",
        f"  {valid}",
        "",
    ])
    return "\n".join(rows)


def generated():
    data = schema_data()
    return {MODULE: render_module(data), DOC: render_docs(data), POLICY: render_policy(data)}


def main():
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    outputs = generated()
    if args.self_test:
        if render_module(schema_data()) != render_module(schema_data()):
            raise ValueError("module generation is not deterministic")
        if render_docs(schema_data()) != render_docs(schema_data()):
            raise ValueError("documentation generation is not deterministic")
        if render_policy(schema_data()) != render_policy(schema_data()):
            raise ValueError("runtime policy generation is not deterministic")
        print("governance schema: ok")
        return 0
    stale = []
    for path, text in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.write_text(text, encoding="utf-8")
    if stale:
        print("stale governance output: " + ", ".join(stale), file=sys.stderr)
        print("run: python3 scripts/gen-governance.py", file=sys.stderr)
        return 1
    if args.check:
        print("governance schema: generated output current")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"gen-governance: {exc}", file=sys.stderr)
        raise SystemExit(1)

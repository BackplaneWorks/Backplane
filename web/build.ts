import { createHash } from "node:crypto";
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { gzipSync } from "node:zlib";

const WEB_DIR = import.meta.dir;
const ROOT = resolve(WEB_DIR, "..");
const SRC_DIR = join(WEB_DIR, "src");
const DIST_DIR = join(WEB_DIR, "dist");
const STYLE_SRC = join(ROOT, "assets/web/style.css");
const I18N_DIR = join(ROOT, "i18n");
const CHECK_ONLY = process.argv.includes("--check");

function walkFiles(dir: string): string[] {
  if (!existsSync(dir)) return [];
  const out: string[] = [];
  for (const name of readdirSync(dir).sort()) {
    if (name.startsWith(".")) continue;
    const full = join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) out.push(...walkFiles(full));
    else if (st.isFile()) out.push(full);
  }
  return out;
}

function sha256(buf: Buffer | string): string {
  return createHash("sha256").update(buf).digest("hex");
}

function parseMsg(path: string): Record<string, string> {
  const map: Record<string, string> = {};
  if (!existsSync(path)) return map;
  for (const raw of readFileSync(path, "utf8").split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq <= 0) continue;
    const key = line.slice(0, eq).trim();
    const val = line.slice(eq + 1).trim();
    if (key) map[key] = val;
  }
  return map;
}

function collectI18nKeys(tsFiles: string[]): string[] {
  const keys = new Set<string>([
    "common.cancel",
    "common.delete",
    "common.save",
    "common.remove",
    "thread.new",
    "settings.lang",
    "palette.newthread",
    "palette.diff",
    "gpui.b.in.reply.to",
    "gpui.follow.paused",
    "gpui.follow.wait",
  ]);
  const re = /\bt\(\s*["']([a-zA-Z0-9_.-]+)["']/g;
  for (const f of tsFiles) {
    const txt = readFileSync(f, "utf8");
    for (const m of txt.matchAll(re)) keys.add(m[1]);
  }
  return [...keys].sort();
}

function buildI18nBundle(tsFiles: string[]): string {
  const keys = collectI18nKeys(tsFiles);
  const catalogs: Record<string, Record<string, string>> = {};
  for (const lang of ["en", "es", "ja"]) {
    const all = parseMsg(join(I18N_DIR, `${lang}.msg`));
    const filtered: Record<string, string> = {};
    for (const k of keys) {
      if (all[k] !== undefined) filtered[k] = all[k];
    }
    catalogs[lang] = filtered;
  }
  return `export const CATALOGS: Record<string, Record<string, string>> = ${JSON.stringify(catalogs)};\n`;
}

function extractBaseTokens(cssText: string): string {
  // Take the canonical :root, html.light, status variables, and reset/button rules
  // from assets/web/style.css (lines 1..90) so the web UI shares the exact desktop palette.
  const lines = cssText.split(/\r?\n/);
  return lines.slice(0, 90).join("\n");
}

function buildCss(): string {
  const parts: string[] = [
    "/* Generated by web/build.ts — tokens from assets/web/style.css */",
    extractBaseTokens(readFileSync(STYLE_SRC, "utf8")),
    readFileSync(join(SRC_DIR, "shell.css"), "utf8"),
  ];
  const respCss = join(SRC_DIR, "viewers/responsive.css");
  if (existsSync(respCss)) {
    parts.push(readFileSync(respCss, "utf8"));
  }
  return parts.join("\n\n") + "\n";
}

async function buildInto(outDir: string): Promise<void> {
  const assetsDir = join(outDir, "assets");
  mkdirSync(assetsDir, { recursive: true });

  const tsFiles = walkFiles(SRC_DIR).filter((f) => f.endsWith(".ts"));
  const i18nSource = buildI18nBundle(tsFiles);

  const i18nPlugin: Bun.BunPlugin = {
    name: "backplane-i18n",
    setup(build) {
      build.onResolve({ filter: /^virtual:i18n$/ }, () => ({
        path: "virtual:i18n",
        namespace: "bp-i18n",
      }));
      build.onLoad({ filter: /.*/, namespace: "bp-i18n" }, () => ({
        contents: i18nSource,
        loader: "ts",
      }));
    },
  };

  const viewerPanePath = join(SRC_DIR, "viewers/viewer-pane.ts");
  const viewerPlugin: Bun.BunPlugin = {
    name: "backplane-viewer-pane",
    setup(build) {
      build.onResolve({ filter: /^virtual:viewer-pane$/ }, () =>
        existsSync(viewerPanePath)
          ? { path: viewerPanePath }
          : { path: "virtual:viewer-pane", namespace: "bp-viewer-stub" },
      );
      build.onLoad({ filter: /.*/, namespace: "bp-viewer-stub" }, () => ({
        contents: "export const mountViewerPane = null;\n",
        loader: "ts",
      }));
    },
  };

  const entrypoints = [join(SRC_DIR, "app.ts"), join(SRC_DIR, "pair.ts")];
  const workerEntry = join(SRC_DIR, "viewers/mesh-worker.ts");
  if (existsSync(workerEntry)) entrypoints.push(workerEntry);

  const res = await Bun.build({
    entrypoints,
    outdir: assetsDir,
    target: "browser",
    format: "esm",
    minify: true,
    sourcemap: "none",
    splitting: false,
    naming: "[name].[ext]",
    plugins: [i18nPlugin, viewerPlugin],
  });
  if (!res.success) {
    for (const log of res.logs) console.error(log);
    process.exit(1);
  }

  // Copy HTML shells and favicons
  writeFileSync(join(outDir, "index.html"), readFileSync(join(SRC_DIR, "index.html")));
  writeFileSync(join(outDir, "pair.html"), readFileSync(join(SRC_DIR, "pair.html")));
  writeFileSync(join(assetsDir, "style.css"), buildCss(), "utf8");
  for (const icon of ["favicon.svg", "favicon-light.svg"]) {
    const src = join(ROOT, "assets/web", icon);
    if (existsSync(src)) writeFileSync(join(assetsDir, icon), readFileSync(src));
  }

  // Compute deterministic manifest of outputs and inputs
  const inputs: Record<string, string> = {};
  for (const f of [
    ...walkFiles(SRC_DIR),
    join(WEB_DIR, "build.ts"),
    STYLE_SRC,
    join(ROOT, "assets/web/favicon.svg"),
    join(ROOT, "assets/web/favicon-light.svg"),
    join(I18N_DIR, "en.msg"),
    join(I18N_DIR, "es.msg"),
    join(I18N_DIR, "ja.msg"),
  ]) {
    if (existsSync(f)) inputs[relative(ROOT, f).replace(/\\/g, "/")] = sha256(readFileSync(f));
  }

  const outputs: Record<string, { bytes: number; gzipBytes: number; sha256: string }> = {};
  let totalAssetGz = 0;
  for (const f of walkFiles(outDir)) {
    const rel = relative(outDir, f).replace(/\\/g, "/");
    const buf = readFileSync(f);
    const gz = gzipSync(buf, { level: 9 }).length;
    outputs[rel] = { bytes: buf.length, gzipBytes: gz, sha256: sha256(buf) };
    if (rel.endsWith(".js") || rel.endsWith(".css")) totalAssetGz += gz;
  }

  const manifest = {
    version: 1,
    totalAssetGzipBytes: totalAssetGz,
    inputs,
    outputs,
  };
  writeFileSync(join(outDir, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n", "utf8");
}

function compareDirs(expected: string, actual: string): string[] {
  const diffs: string[] = [];
  const expFiles = walkFiles(expected).map((f) => relative(expected, f));
  const actFiles = walkFiles(actual).map((f) => relative(actual, f));
  const all = new Set([...expFiles, ...actFiles]);
  for (const rel of [...all].sort()) {
    const a = join(expected, rel);
    const b = join(actual, rel);
    if (!existsSync(b)) diffs.push(`missing in web/dist: ${rel}`);
    else if (!existsSync(a)) diffs.push(`extra in web/dist: ${rel}`);
    else if (!readFileSync(a).equals(readFileSync(b))) diffs.push(`stale in web/dist: ${rel}`);
  }
  return diffs;
}

if (CHECK_ONLY) {
  const stage = mkdtempSync(join(tmpdir(), "bp-web-check-"));
  try {
    await buildInto(stage);
    const diffs = compareDirs(stage, DIST_DIR);
    if (diffs.length > 0) {
      console.error("web/dist is out of date with web/src (run scripts/build-web.sh):");
      for (const d of diffs) console.error("  " + d);
      process.exit(1);
    }
    const m = JSON.parse(readFileSync(join(DIST_DIR, "manifest.json"), "utf8"));
    console.log(`web/dist is up to date (JS+CSS ${(m.totalAssetGzipBytes / 1024).toFixed(1)} KB gz)`);
  } finally {
    rmSync(stage, { recursive: true, force: true });
  }
} else {
  const stage = mkdtempSync(join(tmpdir(), "bp-web-build-"));
  try {
    await buildInto(stage);
    rmSync(DIST_DIR, { recursive: true, force: true });
    mkdirSync(DIST_DIR, { recursive: true });
    for (const f of walkFiles(stage)) {
      const rel = relative(stage, f);
      const dst = join(DIST_DIR, rel);
      mkdirSync(dirname(dst), { recursive: true });
      writeFileSync(dst, readFileSync(f));
    }
    const m = JSON.parse(readFileSync(join(DIST_DIR, "manifest.json"), "utf8"));
    console.log(`built web/dist (JS+CSS ${(m.totalAssetGzipBytes / 1024).toFixed(1)} KB gz)`);
  } finally {
    rmSync(stage, { recursive: true, force: true });
  }
}

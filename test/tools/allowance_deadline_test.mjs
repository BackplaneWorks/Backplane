import assert from 'node:assert/strict';
import {allowanceDeadline} from '../../src/web/allowance-deadline.js';
const element = values => {
  const attrs = new Map(Object.entries(values));
  return {getAttribute: k => attrs.get(k) ?? null, setAttribute: (k,v) => attrs.set(k,v), removeAttribute: k => attrs.delete(k)};
};
const chip=element({'data-as-of':'1000','data-valid-until':'1100'}), details=element({});
const root={querySelector: id => id==='#allowance-chip'?chip:details};
let time=1000, queued, canceled=0;
const update=allowanceDeadline({clock:()=>time, schedule:(f,ms)=>{queued={f,ms};return 1;}, cancel:()=>{canceled++;}});
update(root); assert.equal(queued.ms,100000);
queued.f(); assert.equal(chip.getAttribute('data-retired'),'true'); assert.equal(details.getAttribute('data-retired'),'true');
update(root); assert.equal(chip.getAttribute('data-retired'),'true','same picture never revives');
chip.setAttribute('data-as-of','1001');update(root);assert.equal(chip.getAttribute('data-retired'),null,'a new server picture may display its valid reading');
time=1200;update(root);assert.equal(chip.getAttribute('data-retired'),'true','past deadline retires immediately');
chip.setAttribute('data-as-of','1300');chip.setAttribute('data-valid-until','1400');time=1000;update(root);assert.equal(queued.ms,100000,'clock behind cannot extend lifetime');
update(root,false);assert.equal(chip.getAttribute('data-retired'),'true','cached/disconnected picture is retired');
update(root,true);assert.equal(chip.getAttribute('data-retired'),'true','reconnect needs a fresh picture');
chip.setAttribute('data-as-of','bad');update(root);assert.equal(chip.getAttribute('data-retired'),null,'unknown server label remains unknown');
assert(canceled>0);console.log('allowance presentation deadline: PASS');

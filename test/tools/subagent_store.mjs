const got=query.values('@sub:t1',400);
let count=0;const check=(name,a,b)=>{assert.deepEqual(a,b,name);console.log('ok '+name);count++};
check('production query retains both starts beyond shared page',got.filter(r=>r[7].startsWith('start')).length,2);

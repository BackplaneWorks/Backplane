import assert from 'node:assert/strict';
import { Database } from 'bun:sqlite';
import {pathToFileURL} from 'node:url';
const lib=(await import(pathToFileURL(process.argv[2]).href)).default;
const list=xs=>xs.reduceRight((tail,head)=>({$: 'Con',head,tail}),{$:'Nil'});
const rows=xs=>list(xs.map(r=>list(r.map(String))));
const db=new Database(':memory:');
db.exec(lib.schema());
const insert=db.prepare('INSERT INTO entry VALUES(?,?,?,?,?,?,?,?,?,?)');let seq=0;
const add=(thread,call,kind,text,at=200)=>{const n=++seq;insert.run(n,n,call+'/'+n,thread,'','act',call,kind,text,at)};
add('@sub:t1','c1','start:subagent','Review power',100);
for(let n=12;n>0;n--)add('@sub:t1','c1','Bash','Inspect '+n+'\nPrivate multiline body');
add('@sub:t1','c1','end','completed',201);
add('@sub:t1','c2','start:subagent','Review routing',202);
for(let n=450;n>0;n--)add('@sub:t1','c2','Bash','Inspect '+n);
add('@sub:t1','c2','end','completed',203);
for(let n=0;n<500;n++)add('@sub:other','c1',n===0?'start:subagent':'Bash','Foreign secret '+n,204);

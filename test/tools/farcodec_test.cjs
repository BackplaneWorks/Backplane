const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const zlib = require('node:zlib');
const source = fs.readFileSync('src/server/effects/farcodec.js', 'utf8').replace(/^io_eff\(CID\(FarCodec\..*$/gm, '');
const ctx = { require, Buffer, TextDecoder, CID: x => x, Con: 'Con', Nil: 'Nil' };
vm.createContext(ctx);
vm.runInContext(source + '\nthis.pack = far_codec_pack; this.unpack = far_codec_unpack;', ctx);
const list = bytes => [...bytes].reduceRight((tail, head) => ({ $: 'Con', head, tail }), { $: 'Nil' });
const bytes = xs => { const a = []; for (; xs.$ === 'Con'; xs = xs.tail) a.push(xs.head); return Buffer.from(a); };
const response = (status, body) => list(Buffer.from(`HTTP/1.1 ${status}\r\nContent-Type: application/json\r\nContent-Length: ${Buffer.byteLength(body)}\r\n\r\n${body}`));
const body = out => out.subarray(out.indexOf('\r\n\r\n') + 4).toString();
const sample = JSON.stringify({ items: Array.from({length: 100}, (_, i) => ({ n: i, text: 'A message with accents é and emoji 🐈' })) });
const packed = bytes(ctx.pack(response('200 OK', sample)));
assert.ok(packed.length < Buffer.byteLength(sample));
assert.equal(ctx.unpack(body(packed)), sample);
assert.equal(ctx.unpack(sample), sample);
assert.equal(ctx.unpack('temporarily unavailable'), 'temporarily unavailable');
const small = response('200 OK', '{}'); assert.deepEqual(bytes(ctx.pack(small)), bytes(small));
const denied = response('403 Forbidden', sample); assert.deepEqual(bytes(ctx.pack(denied)), bytes(denied));
assert.equal(ctx.unpack(JSON.stringify({ farEncoding: 'gzip-base64-v1', data: 'invalid!' })), '');
assert.equal(ctx.unpack(JSON.stringify({ farEncoding: 'unknown', data: '' })), '');
// Exercise the same bound at a small test-only limit, without a stress load.
const bounded = { require, Buffer, TextDecoder, CID: x => x, Con: 'Con', Nil: 'Nil' };
vm.createContext(bounded);
vm.runInContext(source.replace('const FAR_CODEC_LIMIT = 1048576;', 'const FAR_CODEC_LIMIT = 128;') + '\nthis.unpack = far_codec_unpack;', bounded);
const large = Buffer.from(JSON.stringify({text: 'x'.repeat(128)}));
assert.equal(bounded.unpack(JSON.stringify({ farEncoding: 'gzip-base64-v1', data: zlib.gzipSync(large).toString('base64') })), '');
console.log('far codec: roundtrip, compatibility, bounded decoding and invalid input passed');

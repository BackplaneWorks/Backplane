// What the policy keeps of a files.dir read, and which of the request's fm.* info keys survive adoption. usage: bun debug_fm.mjs BIN LOG PORT
import {spawn} from 'node:child_process';import {readFileSync} from 'node:fs';import net from 'node:net';
const [bin,log,port]=process.argv.slice(2);
const p=spawn('sh',['-c',`ulimit -s 1048576; exec ${bin} ${port}`],{stdio:['ignore','pipe','inherit']});
await new Promise(r=>p.stdout.once('data',r));
const s=net.connect(Number(port),'127.0.0.1');await new Promise(r=>s.once('connect',r));
let buf='',w=null;s.on('data',d=>{buf+=d;let i;while((i=buf.indexOf('\n'))>=0){const l=buf.slice(0,i);buf=buf.slice(i+1);w?.(l)}});
const ask=l=>new Promise(r=>{w=r;s.write(l+'\n')});
const lines=readFileSync(log,'utf8').trim().split('\n');
await ask('F '+JSON.stringify({t:'log',since:0,origin:'1',version:'x',info:{},items:lines.slice(0,200).map(x=>JSON.parse(x))}));
for(let i=200;i<lines.length;i+=200)await ask('F '+JSON.stringify({t:'changes',items:lines.slice(i,i+200).map(x=>JSON.parse(x))}));
const th=JSON.parse(lines.find(l=>l.includes('"ThreadCreated"'))).id;
const V=async(extra)=>JSON.parse(await ask('V '+JSON.stringify({hub:'h',cid:'c',now:1.8e12,target:{kind:'thread',id:th},action:'',value:'',...extra})));
const sess=(info)=>({sel:th,rid:1,drafts:{},open:{},adding:false,panel:false,info});
const keys=r=>Object.keys(r.session?.info||{}).filter(k=>k.startsWith('fm.')||k.startsWith('pdf.'));
const a=await V({session:sess({'fm.req:7':th,['fm.id:'+th]:'7',['fm.want:'+th]:''})});
console.log('thread',th);console.log('info fm.* kept after adopt, no read:',JSON.stringify(keys(a)));
const b=await V({session:sess({'fm.req:7':th,['fm.id:'+th]:'7',['fm.want:'+th]:''}),reads:[{kind:'files.dir',id:7,result:{fmEntries:'d\t0\tsrc',fmDir:'',fmRoot:'/tmp',thread:th}}]});
console.log('with read:',JSON.stringify(keys(b)),'list=',JSON.stringify(b.session?.info?.['fm.list:'+th]));
const c=await V({session:sess({'fm.req:7':th,['fm.id:'+th]:'7',['fm.want:'+th]:''}),reads:[{kind:'files.dir',id:7,result:{fmEntries:'d\t0\tsrc',fmDir:'',fmRoot:'/tmp',thread:th}}]});
p.kill();process.exit(0);

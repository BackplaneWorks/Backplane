// Capture the real hub's raw frames for a short session (reference for the slim host).
import {mkdirSync,writeFileSync,rmSync} from 'node:fs';
import {makeStandins,startHub,stopHub,client,sleep} from '../perf/lib.mjs';
const R='/home/h/Documents/i2cjak/backplane-gpui';
const root=R+'/build/gpui/slim-run/cap';rmSync(root,{recursive:true,force:true});mkdirSync(root,{recursive:true});
makeStandins(root+'/bin');
const h=await startHub({bin:R+'/build/gpui/backplane-serve',home:root+'/home',port:3820,standins:root+'/bin',extraEnv:{FAKE_SECS:'3',FAKE_PER:'2',FAKE_CYCLE:'5'}});
const frames=[];
const c=await client(h,{onMsg:(o,now,n)=>frames.push({now,n,o})});
mkdirSync(root+'/proj',{recursive:true});
await sleep(1500);
const mark=frames.length;
c.send('project.add',{path:root+'/proj'});const pc=await c.until(10000,()=>c.seen.find(x=>x.$==='ProjectCreated'));
c.send('thread.create',{project:pc.id,title:'t',env:'local'});
const th=await c.until(10000,()=>c.seen.find(x=>x.$==='ThreadCreated'));
c.send('turn.start',{thread:th.id,text:'hello'});
await sleep(6000);
const r=await c.rpc('load.ping',{});
writeFileSync(R+'/build/gpui/results/slim/capture-raw.json',JSON.stringify({hello:await (await fetch(h.url+'/hello')).text(),frames:frames.map(f=>({n:f.n,o:f.o})),ping:r},null,1));
stopHub(h);await sleep(500);process.exit(0);

// Small-scale check of slim_serve's V fields (p.now, overlay, p.window). usage: bun policy_fields.mjs BIN LOG PORT (capped, fixture logs only)
import {spawn} from 'node:child_process';import {readFileSync} from 'node:fs';import net from 'node:net';
const [bin,log,port]=process.argv.slice(2);
const p=spawn('sh',['-c',`ulimit -s 1048576; exec ${bin} ${port}`],{stdio:['ignore','pipe','inherit']});
await new Promise(r=>p.stdout.once('data',r));
const s=net.connect(Number(port),'127.0.0.1');await new Promise(r=>s.once('connect',r));
let buf='',w=null;s.on('data',d=>{buf+=d;let i;while((i=buf.indexOf('\n'))>=0){const l=buf.slice(0,i);buf=buf.slice(i+1);w?.(l)}});
const ask=l=>new Promise(r=>{w=r;s.write(l+'\n')});
const ascii=t=>t.replace(/[\u0080-￿]/g,c=>'\\u'+c.charCodeAt(0).toString(16).padStart(4,'0'));
const lines=readFileSync(log,'utf8').trim().split('\n');
await ask('F '+ascii(JSON.stringify({t:'log',since:0,origin:'1',version:'x',info:{},items:lines.slice(0,200).map(x=>JSON.parse(x))})));
for(let i=200;i<lines.length;i+=200)await ask('F '+ascii(JSON.stringify({t:'changes',items:lines.slice(i,i+200).map(x=>JSON.parse(x))})));
const sel=process.env.SEL||'';const sess={sel,rid:1,drafts:{},open:{},adding:false,panel:false,info:{}};
const base={hub:'h',cid:'c',session:sess,target:sel?{kind:'thread',id:sel}:{kind:'recent',id:''},action:'',value:''};
const v=async(extra)=>JSON.parse(await ask('V '+JSON.stringify({...base,...extra})));
const first=l=>l.projects?.[0]?.threads?.[0];
const a=await v({});console.log('no now:   ago =',first(a.shown)?.ago,'| keys',Object.keys(a).join(','));
const b=await v({now:1785000000*1000+102*86400*1000});console.log('now given: ago =',first(b.shown)?.ago);
const win={ids:['1'],messageIds:[],historyUnits:[],contextMessages:[],partial:[],anchor:{id:'',offset:0},older:'',olderNext:'',hasMore:false,remaining:68,newer:0,total:1};
const c=await v({now:1785000000*1000+102*86400*1000,window:win});console.log('with window: overlay keys',Object.keys(c.overlay||{}).join(','),'| thread earlier =',c.shown.thread?.earlier,'| overlay.j keys sample',Object.keys(c.overlay?.j||{}).slice(0,4).join(','));
p.kill();process.exit(0);

CREATE TABLE meta(k TEXT PRIMARY KEY, v TEXT);
CREATE TABLE line(seq INTEGER PRIMARY KEY, off INTEGER, len INTEGER, wire TEXT);
CREATE TABLE entry(seq INTEGER PRIMARY KEY, ord INTEGER UNIQUE, id TEXT, thread TEXT, src TEXT, kind TEXT, role TEXT, akind TEXT, text TEXT, at INTEGER);
CREATE INDEX entry_thread ON entry(thread, seq);
CREATE INDEX entry_src ON entry(src, seq) WHERE src <> '';
CREATE INDEX entry_id ON entry(id);
CREATE INDEX entry_user ON entry(thread, at) WHERE kind = 'msg' AND role = 'user';
CREATE INDEX entry_tone ON entry(thread, role, seq) WHERE kind = 'act';
CREATE VIRTUAL TABLE entry_fts USING fts5(text, content='entry', content_rowid='seq', tokenize='unicode61 remove_diacritics 0');
CREATE TABLE term(word TEXT, ord INTEGER, PRIMARY KEY(word, ord)) WITHOUT ROWID;
CREATE TABLE post(seq INTEGER PRIMARY KEY, id TEXT, room TEXT, src TEXT, text TEXT, hop INTEGER, at INTEGER);
CREATE INDEX post_room ON post(room, seq);
CREATE INDEX post_room_id ON post(room, id);
CREATE TABLE mail(seq INTEGER PRIMARY KEY, id TEXT, conv TEXT, src TEXT, dst TEXT, kind TEXT, ref TEXT, want TEXT, head TEXT, size INTEGER, at INTEGER);
CREATE INDEX mail_conv ON mail(conv, seq);
CREATE INDEX mail_newest ON mail(conv, at, seq);
CREATE INDEX mail_id ON mail(id);
CREATE TABLE project(id TEXT PRIMARY KEY, title TEXT, root TEXT, created INTEGER, removed INTEGER, json TEXT);
CREATE TABLE thread(id TEXT PRIMARY KEY, project TEXT, title TEXT, created INTEGER, activity INTEGER, turn TEXT, pending INTEGER, archived INTEGER, pinned INTEGER, settled_at INTEGER, provider TEXT, model TEXT, session TEXT, deleted INTEGER, json TEXT);
CREATE INDEX thread_project ON thread(project, activity);
CREATE TABLE task(id TEXT PRIMARY KEY, parent TEXT, child TEXT, state TEXT, delivered INTEGER, json TEXT);
CREATE INDEX task_parent ON task(parent);
CREATE INDEX task_child ON task(child);
CREATE TABLE ask(id TEXT PRIMARY KEY, thread TEXT, open INTEGER, json TEXT);
CREATE INDEX ask_thread ON ask(thread);
CREATE TABLE queue(thread TEXT PRIMARY KEY, n INTEGER, json TEXT);
CREATE TABLE setting(k TEXT PRIMARY KEY, v TEXT, cold INTEGER);
CREATE VIEW work AS SELECT substr(k, 1, instr(k, '.') - 1) AS kind, substr(k, instr(k, '.') + 1) AS thread, v AS rows FROM setting WHERE k GLOB 'bg.*' OR k GLOB 'watch.*';
CREATE VIEW lock AS SELECT substr(k, 6) AS name, v AS json FROM setting WHERE k GLOB 'lock.*';
CREATE TABLE bot(id TEXT PRIMARY KEY, name TEXT, thread TEXT, deleted INTEGER, json TEXT);
CREATE TABLE room(id TEXT PRIMARY KEY, name TEXT, deleted INTEGER, json TEXT);
CREATE TABLE routine(id TEXT PRIMARY KEY, bot TEXT, on_ INTEGER, deleted INTEGER, json TEXT);
CREATE INDEX routine_bot ON routine(bot);
CREATE TABLE conv(id TEXT PRIMARY KEY, kind TEXT, project TEXT, last INTEGER, want TEXT, parts TEXT, json TEXT);
CREATE TABLE mark(k TEXT PRIMARY KEY, bot TEXT, conv TEXT, status TEXT, json TEXT);
CREATE INDEX mark_bot ON mark(bot);
CREATE TABLE far_line(seq INTEGER PRIMARY KEY, scope TEXT);
CREATE INDEX far_line_scope ON far_line(scope, seq);
CREATE TABLE obj(domain TEXT, key TEXT, json TEXT, PRIMARY KEY(domain, key)) WITHOUT ROWID;

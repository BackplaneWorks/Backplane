#!/usr/bin/env python3
"""Generate native/host/src/bots/mail/prompt_text.rs: the words of Bots.prompt.* (src/core/bothub.bend) as Rust literals, so they cannot drift. Run from the repo root."""
src = open('src/core/bothub.bend').read().split('\n')
def find(prefix): return next(i for i, l in enumerate(src) if l.startswith(prefix))
def strings(lines):
    t, out, i = '\n'.join(lines), [], 0
    while i < len(t):
        if t[i] == '"':
            j = i + 1
            while t[j] != '"': j += 2 if t[j] == '\\' else 1
            out.append(t[i + 1:j]); i = j + 1
        else: i += 1
    return out
def join(parts): return ''.join(parts)
u = strings(src[find('def Bots.prompt.uber'):find('def Bots.prompt.k')])
assert u[-1] == '', u[-1:]
uber = join(u[:-1])
k = strings(src[find('def Bots.prompt.k'):find('# the bot part of a thread')])
# literals, in order: head | name | home | /bots/ .. | id | ". People see.." | "" | persona head | persona tail | how you work ... Hop | ... zone | " (" | "), ..."
i_empty = k.index('')
assert k[3] == '/bots/', k[3]
head, you, bots, see = k[0], k[1], k[2], join(k[4:i_empty])
persona_head, persona_tail = k[i_empty + 1], k[i_empty + 2]
rest = k[i_empty + 3:]
hop = next(n for n, x in enumerate(rest) if x.startswith('Conversations between bots stop after '))
stop = next(n for n, x in enumerate(rest) if n > hop and x.startswith(' messages;'))
zone = next(n for n, x in enumerate(rest) if x.startswith('which is '))
src_at = next(n for n, x in enumerate(rest) if x == ' (')
parts = [join(rest[:hop + 1]), join(rest[stop:zone + 1]), rest[src_at], join(rest[src_at + 1:])]
run = strings(src[find('def Bots.prompt.scoped'):find('def Bots.prompt.private')])
run = [x for x in run if x.startswith('\\n# Private') or x.startswith('. Use mail_context') or x == '\\n']
assert len(run) == 3, len(run)
assess = strings(src[find('def Bots.prompt.assessments'):find('def Bots.prompt.scoped')])
assess = [x for x in assess if x]
q = lambda s: '"' + s + '"'
with open('native/host/src/bots/mail/prompt_text.rs', 'w') as f:
    f.write('//! Generated by test/gpui/bots/gen_bot_prompt.py from src/core/bothub.bend: the words of Bots.prompt.*. Do not edit.\n')
    f.write(f'pub const UBER: &str = {q(uber)};\n')
    f.write(f'pub const HEAD: [&str; 4] = [{q(head)}, {q(you)}, {q(bots)}, {q(see)}];\n')
    f.write(f'pub const PERSONA: [&str; 2] = [{q(persona_head)}, {q(persona_tail)}];\n')
    f.write('pub const WORK: [&str; 4] = [' + ', '.join(q(p) for p in parts) + '];\n')
    f.write(f'pub const RUN: [&str; 2] = [{q(run[0])}, {q(run[1])}];\n')
    f.write('pub const ASSESS: [&str; 2] = [' + ', '.join(q(a) for a in assess) + '];\n')

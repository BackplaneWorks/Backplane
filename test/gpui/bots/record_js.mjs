// Record the JS hub's events for one bots scenario (the oracle for the Rust port, native/host/src/bots/tests.rs `js_parity`).
// usage: bun test/gpui/bots/record_js.mjs OUTDIR     (JS_HUB=build/gpui/backplane-serve PORT=3910; a temp home; stand-in agents only)
import {mkdirSync,copyFileSync,writeFileSync} from 'node:fs';
import {startHub,stopHub,makeStandins,client,sleep} from '../perf/lib.mjs';
import {makeFixture} from '../parity/fixture.mjs';
import {execFileSync} from 'node:child_process';
const out=process.argv[2],scen=process.argv[3]||'bots';
const bin=process.env.JS_HUB||'build/gpui/backplane-serve',port=Number(process.env.PORT||3910);
const work=out+'/work';mkdirSync(work+'/fixroot',{recursive:true});
const home=work+'/home';makeFixture(home,work+'/fixroot');makeStandins(work+'/bin');
const h=await startHub({bin,home,port,cap:'3700M',standins:work+'/bin',extraEnv:{FAKE_SECS:'1',FAKE_PER:'2',FAKE_CYCLE:'5',TZ:'Etc/UTC'}});
console.log(execFileSync('test/gpui/slim/check_agents.sh',[String(h.pid),work+'/bin']).toString().trim());
await sleep(4000);
const c=await client(h);
const R=async(m,p)=>{const r=await c.rpc(m,p);const o=r?.o;return {ok:o?.ok,error:o?.error,bot:o?.bot}};
const steps=[];const S=async(name,m,p)=>{const r=await R(m,p);steps.push({name,m,ok:r.ok,error:r.error??null});await sleep(250);return r};
if(scen==='mail1'){
const ada=(await S('create ada','bots.create',{name:'ada'})).bot;
const bob=(await S('create bob','bots.create',{name:'bob'})).bot;
await S('mail on','setting.set',{key:'mail.on',value:'on'});
await S('room r1','bots.room',{room:'r1',name:'lab',members:`${ada}\n${bob}`});
await S('post p1 (mail on)','bots.post',{room:'r1',text:'hello all',msg:'p1'});
await S('post p1 again','bots.post',{room:'r1',text:'hello all',msg:'p1'});
await S('routine ro1','bots.routine',{bot:ada,routine:'ro1',name:'later',at:'in 3d',prompt:'do it'});
await S('run ro1 (mail on)','bots.routine_run',{routine:'ro1'});
await sleep(1500);
await S('mail off','setting.set',{key:'mail.on',value:'off'});
const bub=(await S('create bub uber','bots.create',{name:'bub',uber:true})).bot;
await sleep(3000);
await S('room r2 with the uberbot','bots.room',{room:'r2',name:'ops',members:`${bub}\n${ada}`});
await S('post p2 (uberbot in the room)','bots.post',{room:'r2',text:'status?',msg:'p2'});
await S('routine ro2 of the uberbot','bots.routine',{bot:bub,routine:'ro2',name:'morning',at:'in 3d',prompt:'plan the day'});
await S('run ro2 (uberbot)','bots.routine_run',{routine:'ro2'});
await sleep(2500);
}else if(scen==='uber2'){
const bub=(await S('create bub','bots.create',{name:'bub',persona:'dry'})).bot;
await S('remember k1','bots.remember',{bot:bub,key:'k1',kind:'fact',text:'one',tags:'a'});await sleep(1200);
await S('remember k2','bots.remember',{bot:bub,key:'k2',kind:'pref',text:'two',tags:''});await sleep(1200);
await S('remember k3','bots.remember',{bot:bub,key:'k3',kind:'note',text:'three',tags:'c'});await sleep(1200);
await S('remember k1 again','bots.remember',{bot:bub,key:'k1',kind:'fact',text:'one!',tags:'a'});await sleep(1200);
await S('routine rz','bots.routine',{bot:bub,routine:'rz',name:'zed',at:'in 3d',prompt:'z'});
await S('routine ra','bots.routine',{bot:bub,routine:'ra',name:'alpha',schedule:'daily 09:30',prompt:'a'});
await S('routine rm','bots.routine',{bot:bub,routine:'rm',name:'mid',schedule:'weekdays 08:00',prompt:'m'});
await S('routine rb','bots.routine',{bot:bub,routine:'rb',name:'beta',schedule:'every 2h',prompt:'b',on:false});
await S('promote bub','bots.uber',{bot:bub});
await sleep(130000);
await S('uber_home as holder','bots.uber_home',{});
await sleep(1500);
}else if(scen==='uber'){
const ada=(await S('create ada','bots.create',{name:'ada'})).bot;
const bub=(await S('create bub uber','bots.create',{name:'bub',uber:true})).bot;
await sleep(3000);
await S('uber again','bots.uber',{bot:bub});
await S('uber a missing bot','bots.uber',{bot:'p1~b9'});
await sleep(130000);
await S('remember','bots.remember',{bot:bub,key:'Home Town',kind:'fact',text:'Oulu',tags:'x'});
await S('remember on a plain bot','bots.remember',{bot:ada,key:'k',kind:'note',text:'t'});
await S('forget','bots.forget',{bot:bub,key:'Home Town'});
await S('routine','bots.routine',{bot:bub,routine:'ro1',name:'later',at:'in 3d',prompt:'p'});
await S('routine daily','bots.routine',{bot:bub,routine:'ro2',name:'daily',schedule:'daily 09:30',prompt:'q'});
await S('pin here','bots.pin',{routine:'ro2',pin:'here'});
await S('pin unpin','bots.pin',{routine:'ro2',pin:''});
await S('pin a plain bot routine','bots.pin',{routine:'zz',pin:'here'});
await S('routine delete','bots.routine_delete',{routine:'ro1'});
await S('edit bub','bots.edit',{bot:bub,persona:'calm'});
await S('uber_home as holder','bots.uber_home',{});
await S('join with nothing on offer','bots.uber_join',{uid:'u1-x'});
await sleep(1500);
}else if(scen==='routines'){
const ada=(await S('create ada','bots.create',{name:'ada'})).bot;
await S('routine daily','bots.routine',{bot:ada,routine:'ro1',name:'morning',schedule:'daily 09:30',prompt:'good morning'});
await S('routine bad schedule','bots.routine',{bot:ada,name:'x',schedule:'whenever',prompt:'p'});
await S('routine neither','bots.routine',{bot:ada,name:'x',prompt:'p'});
await S('routine both','bots.routine',{bot:ada,name:'x',schedule:'daily 09:30',at:'in 1h',prompt:'p'});
await S('routine bad zone','bots.routine',{bot:ada,name:'x',schedule:'daily 09:30',tz:'not a zone',prompt:'p'});
await S('routine bad time','bots.routine',{bot:ada,name:'x',at:'banana',prompt:'p'});
await S('routine no bot','bots.routine',{bot:'nope',name:'x',schedule:'daily 09:30',prompt:'p'});
await S('routine once soon','bots.routine',{bot:ada,routine:'ro2',name:'soon',at:'in 3s',prompt:'once please'});
await S('routine hourly utc','bots.routine',{bot:ada,routine:'ro3',name:'hourly',schedule:'@hourly',tz:'UTC',prompt:'tick'});
await S('routine toggle off','bots.routine',{bot:ada,routine:'ro3',name:'hourly',prompt:'tick',on:false,keep:true});
await S('run now','bots.routine_run',{routine:'ro1'});
await sleep(2500);
await sleep(6000);
await S('run the done one','bots.routine_run',{routine:'ro2'});
await S('delete ro1','bots.routine_delete',{routine:'ro1'});
await S('run a deleted one','bots.routine_run',{routine:'ro1'});
await S('run an unknown one','bots.routine_run',{routine:'zz'});
await sleep(1500);
}else{
const ada=(await S('create ada','bots.create',{name:'ada',persona:'dry'})).bot;
await S('create ADA again','bots.create',{name:'ADA'});
const bob=(await S('create bob','bots.create',{name:'bob'})).bot;
await S('create bad name','bots.create',{name:'bad name'});
await S('edit ada','bots.edit',{bot:ada,persona:'new'});
await S('edit nobody','bots.edit',{bot:'nope'});
await S('room r1','bots.room',{room:'r1',name:'lab',members:`${ada}\n${bob}\nzed@far`});
await S('post p1','bots.post',{room:'r1',text:'hello all',msg:'p1'});
await sleep(2500);
await S('post p1 again','bots.post',{room:'r1',text:'hello all',msg:'p1'});
await S('post to nobody','bots.post',{room:'nope',text:'x'});
await S('say ada m1','bots.say',{bot:ada,text:'hi',msg:'m1'});
await sleep(2500);
await S('say ada m1 again','bots.say',{bot:ada,text:'hi',msg:'m1'});
await S('remember','bots.remember',{bot:ada,key:' My Key! ',kind:'PREF',text:'t',tags:'x'});
await S('remember odd kind','bots.remember',{bot:ada,key:'k2',kind:'weird',text:'u'});
await S('forget','bots.forget',{bot:ada,key:'k2'});
await S('space','bots.space',{bot:ada,action:'go',value:'x'});
await sleep(2500);
await S('delete bob','bots.delete',{bot:bob});
await S('delete bob again','bots.delete',{bot:bob});
await S('say dead bob','bots.say',{bot:bob,text:'x'});
await S('post with a deleted member','bots.post',{room:'r1',text:'second',msg:'p2'});
await sleep(2500);
await S('room_delete','bots.room_delete',{room:'r1'});
await S('post to deleted room','bots.post',{room:'r1',text:'x'});
}
await sleep(1000);stopHub(h);await sleep(1500);
copyFileSync(home+'/events.jsonl',out+`/events-${scen}.jsonl`);
(()=>{try{execFileSync('cp',['-r',home+'/mail',out+`/mail-${scen}`])}catch{}})();writeFileSync(out+`/steps-${scen}.json`,JSON.stringify(steps,null,1));
console.log('wrote',out+`/events-${scen}.jsonl`);process.exit(0);

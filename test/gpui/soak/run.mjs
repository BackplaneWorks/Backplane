// One hop of the Rust hub soak. bun run.mjs key=value ...
//   bin=PATH hub binary   home=DIR persistent hub home   out=DIR results   secs=N   agents=20   port=N   sample=30
//   policy=PATH bp-policy-serve (optional: a mobile view client then runs, the presenter folds every commit)
//   fresh=1 (wipe home, seed 1 project + N threads)   hop=N   stop=term|kill|none   write_every=10   fake_per=2 fake_cycle=20
// Stand-in agents only (FAKE_* stand-in from test/tools/perf_standin.ts). Event driven client. Samples every `sample` s.
import {mkdirSync,rmSync,writeFileSync,appendFileSync,existsSync,readFileSync} from 'node:fs';
import {execSync} from 'node:child_process';
import {histOf,makeStandins,seedLines,startHub,killHub,client,sleep,pct,rssKb,hwmKb,nthreads,cpuTicks,fdInfo,procs,descendants,zombies,dirBytes,diskFreeKb,originOf,countLines,alive,exists} from './lib.mjs';
import {viewClient} from './view.mjs';
import {guard} from './lib.mjs';
const A=Object.fromEntries(process.argv.slice(2).map(a=>{const i=a.indexOf('=');return [a.slice(0,i),a.slice(i+1)]}));
const secs=Number(A.secs??3600),agents=Number(A.agents??20),port=Number(A.port??3830),sampleS=Number(A.sample??30),hop=Number(A.hop??1);
const home=A.home,out=A.out,bin=A.bin,policy=A.policy||undefined,stop=A.stop??'term',writeEvery=Number(A.write_every??10);
const capKb=Number(A.cap_kb??3.7*1024*1024);
if(!home||!out||!bin){console.error('need bin= home= out=');process.exit(2)}
try{guard({home,port,paths:[out,bin]})}catch(e){console.error(e.message);process.exit(3)}
mkdirSync(out,{recursive:true});
const proj=`${home}/../proj-${port}`;
const log=(...a)=>{const s=`${new Date().toISOString()} hop${hop} ${a.join(' ')}`;console.log(s);appendFileSync(`${out}/run.log`,s+'\n')};
const machine={host:rdOs('hostname'),nproc:Number(rdOs('nproc')),kernel:rdOs('uname -r'),arch:rdOs('uname -m'),commit:A.commit??''};
function rdOs(c){try{return execSync(c,{encoding:'utf8'}).trim()}catch{return ''}}

if(A.fresh==='1'){rmSync(home,{recursive:true,force:true});mkdirSync(home,{recursive:true});mkdirSync(proj,{recursive:true});
 const {lines}=seedLines(proj,agents);
 if(A.seed_file&&existsSync(A.seed_file)){}// synthetic log is generated by gen.py into events.jsonl before the run
 if(!existsSync(`${home}/events.jsonl`))writeFileSync(`${home}/events.jsonl`,lines.join('\n')+'\n')}
mkdirSync(proj,{recursive:true});
const standins=`${home}/../standins`;makeStandins(standins);
// thread ids: from the seed (ts000..) or, for a generated log, any ThreadCreated whose id starts with ts
const ids=[...Array(agents)].map((_,i)=>`ts${String(i).padStart(3,'0')}`);
const before=await countLines(`${home}/events.jsonl`);
before.lines=before.valid; // the hub's cursor counts whole lines only
if(!before.endsWithNewline)log('note: log ends without a newline (torn tail) before start');
const origin=originOf(home);
const dur=secs;
const h=await startHub({bin,home,port,standins,policy,log:`${out}/hub-hop${hop}.log`,extraEnv:{FAKE_SECS:String(dur+900),FAKE_PER:A.fake_per??'2',FAKE_CYCLE:A.fake_cycle??'20'}});
log(`hub pid ${h.pid} up after ${h.bootMs} ms; events before start ${before.lines}; BACKPLANE_AGENTS verified; policy ${policy?'yes':'no'}`);
const bootRss=rssKb(h.pid);

// ---- windows reset at each sample ----
const W={lag:[],ping:[],ack:[],ackFail:0,view:[],viewErr:0,perThread:new Map(),deltas:0,events:0};
let ev0=before.lines;
const stampRe=/@(\d{13})@/;
const wire=await client(h,{since:before.lines,origin,onFrame:(o,t,wall)=>{
 if(o.t==='delta'){W.deltas++;W.perThread.set(o.thread,(W.perThread.get(o.thread)??0)+1);const m=stampRe.exec(o.text??'');if(m)W.lag.push(wall-Number(m[1]))}}});
let eventsTotal=before.lines;wire.onItems=(its,o)=>{if(o.t==='log'||o.t==='changes')eventsTotal+=its.length};
// the join: with since=n and the right origin the hub sends only what is newer than n
const pinger=await client(h,{since:before.lines,origin});
let stopping=false;
(async()=>{while(!stopping){const r=await pinger.rpc('load.ping',{},5000);if(r)W.ping.push(r.ms);else if(!stopping)W.ping.push(5000);await sleep(1000)}})();
// durable-write probe + ledger: project.add acked only after the group commit's fsync
const ledger=`${out}/ledger-hop${hop}.jsonl`;writeFileSync(ledger,'');
let wn=0;
const writer=client(h,{since:before.lines,origin}).then(async wc=>{while(!stopping){const path=`${proj}/w/h${hop}-${wn++}`;const t0=performance.now();const r=await wc.rpc('project.add',{path},20000);
 if(r?.o?.ok){W.ack.push(r.ms);appendFileSync(ledger,JSON.stringify({path,thread:r.o.thread,ms:r.ms})+'\n')}else{W.ackFail++;appendFileSync(ledger,JSON.stringify({path,failed:true,err:r?.o?.error??'timeout'})+'\n')}
 await sleep(writeEvery*1000)}wc.close()});
let view=null;
if(policy){try{view=await viewClient(h,{maxPerSec:Number(A.view_hz??5),onUpdate:r=>{if(r.ok)W.view.push(r.ms);else W.viewErr++}});log(`view client open: first view ${view.openMs?.toFixed(0)} ms`)}catch(e){log('view client failed: '+e.message)}}
// agents: one long streaming turn per thread
let started=0;let fatalEarly=null;let totalDeltas=0;
for(const id of ids){const r=await wire.rpc('turn.start',{thread:id,text:'stream',msg:`soak-h${hop}-${id}`},30000);if(r?.o?.ok)started++;else log(`turn.start ${id}: ${JSON.stringify(r?.o??'timeout')}`)}
log(`${started}/${agents} turns started`);
if(started<agents)fatalEarly=`only ${started}/${agents} turns started`;
for(const k of Object.keys(W))if(Array.isArray(W[k]))W[k].length=0;W.ackFail=0;W.viewErr=0;W.deltas=0;W.perThread.clear(); // the first window starts here, after setup

// ---- sampling ----
const samples=`${out}/samples.jsonl`;const t0=Date.now();let lastCpu=cpuTicks(h.pid),lastT=t0,lastEv=eventsTotal,n=0,fatal=null;
const gOffset=Number(A.offset??0);
const summaryMax={rss:0};
const sample=async()=>{
 const now=Date.now(),all=procs(),kids=descendants(h.pid,all),pol=kids.filter(k=>/policy/.test(k.comm));
 const polRss=pol.reduce((a,p)=>a+rssKb(p.pid),0);
 const lag=W.lag.splice(0),ping=W.ping.splice(0),ack=W.ack.splice(0),view_=W.view.splice(0);const rates=[...W.perThread.values()];const ackFail=W.ackFail,viewErr=W.viewErr;W.ackFail=0;W.viewErr=0;
 const perThread=ids.map(i=>W.perThread.get(i)??0);W.perThread.clear();const deltas=W.deltas;W.deltas=0;totalDeltas+=deltas;
 const cpu=cpuTicks(h.pid),dt=(now-lastT)/1000;
 const fd=fdInfo(h.pid),files=dirBytes(home);
 const s={hop,t:Math.round((now-t0)/1000),T:Math.round((now-t0)/1000)+gOffset,at:now,rss:rssKb(h.pid),hwm:hwmKb(h.pid),polRss,treeRss:rssKb(h.pid)+kids.reduce((a,p)=>a+(rssKb(p.pid)||0),0),
  cpuPct:+(((cpu-lastCpu)/100)/dt*100).toFixed(2),cpuTicks:cpu,threads:nthreads(h.pid),fds:fd.fds,sockets:fd.sockets,kids:kids.length,standins:kids.filter(k=>/claude/.test(k.comm)||k.comm==='sh').length,
  zombies:kids.filter(k=>k.state==='Z').length,events:eventsTotal,evPerS:+((eventsTotal-lastEv)/dt).toFixed(1),logBytes:files['events.jsonl']??0,homeBytes:Object.values(files).reduce((a,b)=>a+b,0),files,diskFreeKb:diskFreeKb(home),
  ping:{n:ping.length,p50:pct(ping,50),p95:pct(ping,95),max:ping.length?Math.max(...ping):NaN,h:histOf(ping)},
  lag:{n:lag.length,p50:pct(lag,50),p95:pct(lag,95),max:lag.length?Math.max(...lag):NaN,h:histOf(lag)},
  deltas,minPerThreadPerS:+(Math.min(...perThread)/dt).toFixed(2),
  ack:{n:ack.length,fail:ackFail,p50:pct(ack,50),p95:pct(ack,95),max:ack.length?Math.max(...ack):NaN,h:histOf(ack)},
  view:{n:view_.length,err:viewErr,p50:pct(view_,50),p95:pct(view_,95),max:view_.length?Math.max(...view_):NaN,h:histOf(view_)}};
 lastCpu=cpu;lastT=now;lastEv=eventsTotal;n++;
 appendFileSync(samples,JSON.stringify(s)+'\n');
 if(s.t>=60&&agents>0&&totalDeltas===0)fatal='no agent stream after 60 s (stand-ins not running?)';
 if(s.rss>capKb)fatal=`hub RSS ${s.rss} kB over the cap ${capKb}`;
 return s};
let exited=null;if(policy&&!view)fatalEarly=(fatalEarly?fatalEarly+'; ':'')+'policy given but the view client did not start';h.exited.then(e=>{exited=e});
while(Date.now()-t0<dur*1000&&!fatal&&!exited){
 await sleep(Math.max(50,sampleS*1000-((Date.now()-t0)%(sampleS*1000))));
 if(exited)break;const s=await sample();
 if(n%10===0)log(`t=${s.t}s rss=${(s.rss/1024).toFixed(0)}MB tree=${(s.treeRss/1024).toFixed(0)}MB cpu=${s.cpuPct}% fds=${s.fds} kids=${s.kids} z=${s.zombies} ev=${s.events} ev/s=${s.evPerS} ping p50/p95=${s.ping.p50?.toFixed(2)}/${s.ping.p95?.toFixed(2)} lag p50=${s.lag.p50?.toFixed(0)} ack p50=${s.ack.p50?.toFixed(1)} fail=${s.ack.fail} view p50=${s.view.p50?.toFixed(1)}/err=${s.view.err} minΔ/s=${s.minPerThreadPerS}`);
}
stopping=true;
if(exited)fatal=fatal??`hub exited during the run: ${JSON.stringify(exited)}`;
if(!exited&&Date.now()-lastT>=15000)await sample();
fatal=fatal??fatalEarly;
const hubPid=h.pid;
// ---- end of hop ----
view?.c.close?.();wire.close();pinger.close();
const endRss=rssKb(hubPid),endEv=eventsTotal;
let after={};
if(!exited&&stop!=='none'){
 const kidsBefore=descendants(hubPid).map(p=>p.pid);
 killHub(h,stop==='kill'?'SIGKILL':'SIGTERM');
 const t1=Date.now();while(exists(hubPid)&&alive(hubPid)&&Date.now()-t1<60000)await sleep(50);
 const stopMs=Date.now()-t1;
 // children must not outlive the hub (stand-ins notice a dead parent within a second)
 let left=kidsBefore;const t2=Date.now();while(Date.now()-t2<10000){left=kidsBefore.filter(p=>exists(p)&&alive(p));if(!left.length)break;await sleep(100)}
 after={stop,stopMs,orphansAfter10s:left.length,zombiesAfter:zombies(procs(),hubPid).length,hubGone:!exists(hubPid)||!alive(hubPid)};
 if(left.length)fatal=fatal??`${left.length} agent processes outlived the hub`;
}
const final=await countLines(`${home}/events.jsonl`);
const sum={hop,machine,secs,agents,fatal,bootMs:h.bootMs,bootRssKb:bootRss,eventsBefore:before.lines,eventsAtEndByWire:endEv,logLinesAfterStop:final.lines,logEndsWithNewline:final.endsWithNewline,samples:n,turnsStarted:started,endRssKb:endRss,after,policy:!!policy,ackFailTotal:null};
writeFileSync(`${out}/hop-${hop}.json`,JSON.stringify(sum,null,1));log('hop done',JSON.stringify(sum));
await writer.catch(()=>{});
process.exit(fatal?4:0);

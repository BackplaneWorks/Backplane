// Record the JS hub's mailroom routing for the uberbot (the oracle for bots/mail/{route,escalate,funnel,tools}.rs): runs, the private lane, dispositions, escalations, a stop's hold, and the funnel.
// usage: bun test/bots/record_triage.mjs OUTDIR     (JS_HUB=build/gpui/backplane-serve PORT=3917; a temp home; stand-in agents only)
import {mkdirSync,writeFileSync,chmodSync,rmSync,readFileSync,copyFileSync,readdirSync} from 'node:fs';
import {startHub,stopHub,client,sleep} from '../perf/lib.mjs';
import {makeFixture} from '../parity/fixture.mjs';
import {execFileSync} from 'node:child_process';
const out=process.argv[2];
const work=out+'/work';rmSync(work,{recursive:true,force:true});mkdirSync(work+'/fixroot',{recursive:true});mkdirSync(work+'/bin',{recursive:true});
const home=work+'/home';makeFixture(home,work+'/fixroot');
writeFileSync(work+'/bin/claude',`#!/bin/sh\nexec bun ${process.cwd()}/test/tools/claude_standin.ts "$@"\n`);chmodSync(work+'/bin/claude',0o755);
for(const n of['codex','grok','muse'])writeFileSync(work+'/bin/'+n,'#!/bin/sh\nexit 1\n'),chmodSync(work+'/bin/'+n,0o755);
const h=await startHub({bin:process.env.JS_HUB||'build/gpui/backplane-serve',home,port:Number(process.env.PORT||3917),standins:work+'/bin',extraEnv:{FAKE_LOG:work+'/fake.log',TZ:'Etc/UTC'}});
console.log(execFileSync('test/slim/check_agents.sh',[String(h.pid),work+'/bin']).toString().trim());
await sleep(3000);const c=await client(h);
const steps=[];const R=async(name,m,p)=>{const o=(await c.rpc(m,p))?.o;steps.push({name,m,ok:o?.ok,error:o?.error??null});await sleep(250);return o};
const fake=()=>{try{return readFileSync(work+'/fake.log','utf8').split('\n')}catch{return[]}};
const urls=()=>Object.fromEntries(fake().filter(l=>l.startsWith('MCP ')).map(l=>l.split(' ')[2]).map(u=>[decodeURIComponent(u.split('/mcp/')[1].split('.')[0].split('?')[0]),u]));
const events=()=>readFileSync(home+'/events.jsonl','utf8').split('\n').filter(Boolean).map(l=>JSON.parse(l));
const waitFor=async(f,ms=15000)=>{const t=Date.now();while(Date.now()-t<ms){const v=f();if(v)return v;await sleep(100)}throw new Error('timed out: '+f)};
let id=0;const calls=[];
const T=async(url,name,args,tag)=>{const r=JSON.parse(await (await fetch(url,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({jsonrpc:'2.0',id:++id,method:'tools/call',params:{name,arguments:args}})})).text());calls.push({tag,name,args,result:r.result??r.error});await sleep(300);return r};
const L=async(url,tag)=>{const r=JSON.parse(await (await fetch(url,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({jsonrpc:'2.0',id:++id,method:'tools/list',params:{}})})).text());calls.push({tag,name:'tools/list',names:(r.result?.tools||[]).map(t=>t.name)});return r};
const lastRun=n=>events().filter(e=>e.$==='RunSet').length>=n&&events().filter(e=>e.$==='RunSet')[n-1];
const ended=th=>events().some(e=>e.$==='TurnChanged'&&e.thread===th&&e.state!=='running');
const ada=(await R('create ada','bots.create',{name:'ada'})).bot;
const bub=(await R('create bub uber','bots.create',{name:'bub',uber:true})).bot;
await sleep(3000);
const bubT=events().find(e=>e.$==='BotSet'&&e.id===bub).thread,adaT=events().find(e=>e.$==='BotSet'&&e.id===ada).thread;
await R('routine a','bots.routine',{bot:bub,routine:'ra',name:'quick',at:'in 3d',prompt:'mode:plain quick report'});
await R('run a: no disposition','bots.routine_run',{routine:'ra'});
let r=await waitFor(()=>lastRun(2));                 // the run (1), its back office (2)
await waitFor(()=>ended(r.thread));await sleep(1500);
await R('routine b','bots.routine',{bot:bub,routine:'rb',name:'slow',at:'in 3d',prompt:'mode:stop slow report'});
await R('run b: disposed','bots.routine_run',{routine:'rb'});
r=await waitFor(()=>lastRun(3));const u3=await waitFor(()=>urls()[r.thread]);await sleep(500);
await L(u3,'run tools');
await T(u3,'mail_dispose',{input:'nope',mode:'done',reason:'x'},'wrong input');
await T(u3,'mail_dispose',{input:r.mail,mode:'done',reason:'routine status'},'done');
await T(u3,'mail_dispose',{input:r.mail,mode:'done',reason:'routine status'},'again');
await T(u3,'decide',{text:'filed it',reason:'routine'},'decide');
await waitFor(()=>ended(r.thread),30000);await sleep(1500);
await R('routine c','bots.routine',{bot:bub,routine:'rc',name:'escalated',at:'in 3d',prompt:'mode:stop to escalate'});
await R('run c: escalated','bots.routine_run',{routine:'rc'});
r=await waitFor(()=>lastRun(4));const u4=await waitFor(()=>urls()[r.thread]);await sleep(500);
await T(u4,'escalate',{to:'person',text:'x'},'no input');
await T(u4,'escalate',{to:'person',text:'mode:stop it finished',input:r.mail,key:'ev-1'},'keyed');
const p=await waitFor(()=>lastRun(5));const u5=await waitFor(()=>urls()[p.thread]);await sleep(500);
await L(u5,'private tools');
await T(u5,'tell_person',{text:'The report is in.',key:'ev-1'},'tell');
await T(u5,'tell_person',{text:'The report is in.',key:'ev-1'},'tell again');
await T(u5,'tell_person',{text:'x',key:'k',extra:'no'},'tell bad args');
await T(u5,'notify_person',{reason:'r',text:'t'},'notify from a back office');
await waitFor(()=>ended(r.thread),30000);await waitFor(()=>ended(p.thread),30000);await sleep(1500);
await R('routine d','bots.routine',{bot:bub,routine:'rd',name:'held',at:'in 3d',prompt:'mode:stop to stop'});
await R('run d: stopped','bots.routine_run',{routine:'rd'});
r=await waitFor(()=>lastRun(6));await waitFor(()=>urls()[r.thread]);await sleep(500);
await R('stop d','turn.interrupt',{thread:r.thread});
await waitFor(()=>ended(r.thread),30000);await sleep(1500);
await R('run d again: held','bots.routine_run',{routine:'rd'});
await sleep(1500);
await R('say ada','bots.say',{bot:ada,text:'mode:plain report please'});
const uA=await waitFor(()=>urls()[adaT]);await waitFor(()=>ended(adaT),30000);await sleep(2500);
await T(uA,'thread_send',{threadId:bubT,text:'mode:plain a word for the uberbot'},'funnel');
await sleep(5000);
stopHub(h);await sleep(1500);
copyFileSync(home+'/events.jsonl',out+'/js-triage.jsonl');
writeFileSync(out+'/js-triage-steps.json',JSON.stringify(steps,null,1));writeFileSync(out+'/js-triage-calls.json',JSON.stringify(calls,null,1));
const mail=[];try{for(const n of readdirSync(home+'/mail').sort())if(n.endsWith('.jsonl'))mail.push({name:n,lines:readFileSync(home+'/mail/'+n,'utf8').split('\n').filter(Boolean)})}catch{}
writeFileSync(out+'/js-triage-mail.json',JSON.stringify(mail,null,1));
console.log('wrote',out,steps.length,'steps',calls.length,'calls');process.exit(0);
